#!/usr/bin/env node
'use strict';

/**
 * Regenerates public/styles.css and public/index.html from the single source of
 * truth, ../mombasa-ni-yetu-polls.html (the Claude-hosted portal).
 *
 * Both versions therefore share one stylesheet and one set of markup, so a
 * design change made in one place cannot drift away from the other. The admin
 * panel is stripped out here: it lives on its own page and must never be served
 * to voters.
 *
 *   npm run build
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'mombasa-ni-yetu-polls.html');
const OUT = path.resolve(__dirname, '..', 'public');

// On a host that only uploads the server/ directory (Vercel with Root
// Directory = server), the source page is not present. The generated files are
// committed, so there is nothing to do - skip rather than fail the deploy.
if (!fs.existsSync(SRC)) {
  console.log('build-public: source page not present here; using the committed '
            + 'public/index.html and public/styles.css as-is.');
  process.exit(0);
}

const src = fs.readFileSync(SRC, 'utf8');

/* ---- stylesheet ---- */
const cssStart = src.indexOf('<style>');
const cssEnd = src.indexOf('</style>');
if (cssStart < 0 || cssEnd < 0) throw new Error('No <style> block found in ' + SRC);
const css = src.slice(cssStart + '<style>'.length, cssEnd).trim();

const reset = `/* Generated by scripts/build-public.js - do not edit by hand.
   Source: mombasa-ni-yetu-polls.html
   The hosted artifact gets this reset from its page skeleton; standalone needs it. */
*{box-sizing:border-box}
html,body{margin:0}
img{max-width:100%}
[hidden]{display:none!important}

`;

/* ---- markup ---- */
const mkStart = cssEnd + '</style>'.length;
const mkEnd = src.indexOf('<script>', mkStart);
if (mkEnd < 0) throw new Error('No <script> block found in ' + SRC);
let markup = src.slice(mkStart, mkEnd).trim();

const adminStart = markup.indexOf('<section class="panel admin" id="adminPanel"');
if (adminStart < 0) throw new Error('Admin panel marker not found - check the source markup');
const mainEnd = markup.indexOf('</main>', adminStart);
const adminEnd = markup.lastIndexOf('</section>', mainEnd) + '</section>'.length;
markup = markup.slice(0, adminStart) + markup.slice(adminEnd);
if (markup.includes('adminPanel')) throw new Error('Admin markup survived the strip');

const head = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Mombasa Ni Yetu Polls</title>
<meta name="description" content="A public opinion poll on the Mombasa governorship race. Unofficial.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wght@500;600;700&family=Inter:wght@400;500;600&display=swap">
<link rel="stylesheet" href="/styles.css">
</head>
<body>
`;
const tail = `
<script src="/socket.io/socket.io.js"></script>
<script src="/app.js"></script>
</body>
</html>
`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'styles.css'), reset + css + '\n');
fs.writeFileSync(path.join(OUT, 'index.html'), head + markup + tail);

console.log(`styles.css  ${fs.statSync(path.join(OUT, 'styles.css')).size} bytes`);
console.log(`index.html  ${fs.statSync(path.join(OUT, 'index.html')).size} bytes (admin markup stripped)`);
